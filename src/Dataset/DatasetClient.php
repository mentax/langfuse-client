<?php

declare(strict_types=1);

namespace Mentax\LangfuseClient\Dataset;

use Generator;
use Mentax\LangfuseClient\Exception\LangfuseException;
use Mentax\LangfuseClient\Exception\NotFoundException;
use Mentax\LangfuseClient\Internal\ArrayReader;
use Mentax\LangfuseClient\Internal\HttpClient;

/**
 * Datasets and dataset items (test cases for experiments).
 */
final readonly class DatasetClient
{
    private const PAGE_SIZE = 100;

    public function __construct(
        private HttpClient $http,
    ) {}

    /**
     * Creates the dataset, or updates description and metadata of an existing one with that name.
     *
     * @param array<string, mixed> $metadata
     */
    public function createDataset(string $name, ?string $description = null, array $metadata = []): Dataset
    {
        $body = ['name' => $name, 'metadata' => (object) $metadata];
        if ($description !== null) {
            $body['description'] = $description;
        }

        return Dataset::fromArray($this->http->post('/api/public/v2/datasets', $body));
    }

    /**
     * @throws NotFoundException
     */
    public function getDataset(string $name): Dataset
    {
        return Dataset::fromArray($this->http->get('/api/public/v2/datasets/' . rawurlencode($name)));
    }

    /**
     * Creates or replaces an item. Writing the same ID again creates a new version of
     * that item; Langfuse keeps the history.
     *
     * Media references in input, expected output or metadata must be the entire value
     * of a field, and the media must be uploaded before the item is written.
     *
     * @param string|null $id stable ID of the test case; generated by Langfuse when null
     */
    public function upsertItem(
        string $datasetName,
        mixed $input,
        mixed $expectedOutput = null,
        mixed $metadata = null,
        ?string $id = null,
        ?string $sourceTraceId = null,
        ?string $sourceObservationId = null,
        DatasetItemStatus $status = DatasetItemStatus::Active,
    ): DatasetItem {
        $body = array_filter(
            [
                'datasetName' => $datasetName,
                'input' => $input,
                'expectedOutput' => $expectedOutput,
                'metadata' => $metadata,
                'id' => $id,
                'sourceTraceId' => $sourceTraceId,
                'sourceObservationId' => $sourceObservationId,
                'status' => $status->value,
            ],
            static fn(mixed $value): bool => $value !== null,
        );

        return DatasetItem::fromArray($this->http->post('/api/public/dataset-items', $body));
    }

    /**
     * @throws NotFoundException
     */
    public function getItem(string $id): DatasetItem
    {
        return DatasetItem::fromArray($this->http->get('/api/public/dataset-items/' . rawurlencode($id)));
    }

    /**
     * Active items of a dataset, fetched page by page. Archived items are skipped
     * client-side, so experiments never run on them.
     *
     * @return Generator<int, DatasetItem>
     *
     * @throws LangfuseException
     */
    public function items(string $datasetName): Generator
    {
        $page = 1;
        do {
            $response = new ArrayReader(
                $this->http->get('/api/public/dataset-items', ['datasetName' => $datasetName, 'page' => $page, 'limit' => self::PAGE_SIZE]),
                'Langfuse dataset items',
            );
            foreach ($response->listOfArrays('data') as $data) {
                $item = DatasetItem::fromArray($data);
                if ($item->status === DatasetItemStatus::Active) {
                    yield $item;
                }
            }
            $totalPages = (new ArrayReader($response->map('meta'), 'Langfuse dataset items meta'))->int('totalPages');
            ++$page;
        } while ($page <= $totalPages);
    }
}
